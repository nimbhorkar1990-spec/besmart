package com.smartsearch.extractor;

import java.time.LocalDateTime;
import java.util.List;

public class ExtractedPageData {

    private String url;
    private String domain;
    private String canonicalUrl;
    private String title;
    private String description;
    private String content;
    private String headings;
    private String keywords;
    private String imageUrl;
    private LocalDateTime publishedDate;
    private String contentHash;
    private double qualityScore;
    private List<String> discoveredInternalLinks;

    public ExtractedPageData() {
    }

    public String getUrl() {
        return url;
    }

    public void setUrl(String url) {
        this.url = url;
    }

    public String getDomain() {
        return domain;
    }

    public void setDomain(String domain) {
        this.domain = domain;
    }

    public String getCanonicalUrl() {
        return canonicalUrl;
    }

    public void setCanonicalUrl(String canonicalUrl) {
        this.canonicalUrl = canonicalUrl;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getContent() {
        return content;
    }

    public void setContent(String content) {
        this.content = content;
    }

    public String getHeadings() {
        return headings;
    }

    public void setHeadings(String headings) {
        this.headings = headings;
    }

    public String getKeywords() {
        return keywords;
    }

    public void setKeywords(String keywords) {
        this.keywords = keywords;
    }

    public String getImageUrl() {
        return imageUrl;
    }

    public void setImageUrl(String imageUrl) {
        this.imageUrl = imageUrl;
    }

    public LocalDateTime getPublishedDate() {
        return publishedDate;
    }

    public void setPublishedDate(LocalDateTime publishedDate) {
        this.publishedDate = publishedDate;
    }

    public String getContentHash() {
        return contentHash;
    }

    public void setContentHash(String contentHash) {
        this.contentHash = contentHash;
    }

    public double getQualityScore() {
        return qualityScore;
    }

    public void setQualityScore(double qualityScore) {
        this.qualityScore = qualityScore;
    }

    public List<String> getDiscoveredInternalLinks() {
        return discoveredInternalLinks;
    }

    public void setDiscoveredInternalLinks(List<String> discoveredInternalLinks) {
        this.discoveredInternalLinks = discoveredInternalLinks;
    }
}

